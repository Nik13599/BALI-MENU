import sharp from 'sharp';
import {readdir,writeFile,stat} from 'node:fs/promises';
const dir='assets/about/photos',manifest={};
let sourceBytes=0,webpBytes=0,avifBytes=0;
for(const name of (await readdir(dir)).filter(x=>/\.JPG$/.test(x)).sort()){
  const path=`${dir}/${name}`,base=name.replace(/\.JPG$/,''),meta=await sharp(path).metadata();
  sourceBytes+=(await stat(path)).size;
  const variants={webp:[],avif:[]};
  for(const width of [320,640,960,1600]){
    for(const format of ['webp','avif']){
      const dest=`${dir}/${base}-${width}.${format}`;
      const buffer=await sharp(path).rotate().resize({width,withoutEnlargement:true})
        .toFormat(format,format==='webp'?{quality:78}:{quality:48,effort:4}).toBuffer({resolveWithObject:true});
      await writeFile(dest,buffer.data);
      variants[format].push({src:dest,width:buffer.info.width,bytes:buffer.data.length});
      if(width===640){if(format==='webp')webpBytes+=buffer.data.length;else avifBytes+=buffer.data.length;}
    }
  }
  manifest[path]={width:meta.width,height:meta.height,...variants};
}
await writeFile('assets/about/photo-manifest.js','// Generated by npm run build:images. Originals remain available.\nexport const photos='+JSON.stringify(manifest)+';\n');
console.log(JSON.stringify({photos:Object.keys(manifest).length,sourceBytes,gallery640WebpBytes:webpBytes,gallery640AvifBytes:avifBytes}));
